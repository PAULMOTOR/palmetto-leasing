export const ROTATING_ARRIVALS: SeedVehicle[] = [];

export function slugifyVehicle(v: Pick<SeedVehicle, "year" | "make" | "model" | "trim" | "external_id">): string {
  const base = [v.year, v.make, v.model, v.trim]
    .filter(Boolean)
    .join("-")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `${base}-${v.external_id.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`.slice(0, 96);
}

export function dealerListingUrl(dealerId: string, listingPath: string): string {
  const d = DEALERS.find((x) => x.id === dealerId);
  if (!d) return listingPath;
  try {
    const base = d.inventory_url.endsWith("/") ? d.inventory_url : `${d.inventory_url}/`;
    return new URL(listingPath.replace(/^\//, ""), base).toString();
  } catch {
    return d.inventory_url;
  }
}

